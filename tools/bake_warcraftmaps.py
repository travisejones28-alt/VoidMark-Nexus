"""Build Data/SpawnsExtra.lua: herb stops from warcraftmaps.com that Nexus's spawn list is missing.

Input: tools/data/warcraftmaps_herb_stops.txt (stop centres per herb/zone, map percent, with node counts).
A stop is added only when Nexus has no spawn of that herb within MATCH (map fraction) of it, so stops
Nexus already covers (its route grouping is 60 yd) are not doubled. Re-run after updating either file.
"""
import collections, math, re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
MATCH = 0.02
ZONES = {"Durotar":1411,"Mulgore":1412,"The Barrens":1413,"Alterac Mountains":1416,"Arathi Highlands":1417,
 "Badlands":1418,"Blasted Lands":1419,"Tirisfal Glades":1420,"Silverpine Forest":1421,"Western Plaguelands":1422,
 "Eastern Plaguelands":1423,"Hillsbrad Foothills":1424,"The Hinterlands":1425,"Dun Morogh":1426,"Searing Gorge":1427,
 "Burning Steppes":1428,"Elwynn Forest":1429,"Duskwood":1431,"Loch Modan":1432,"Redridge Mountains":1433,
 "Stranglethorn Vale":1434,"Swamp of Sorrows":1435,"Westfall":1436,"Wetlands":1437,"Teldrassil":1438,"Darkshore":1439,
 "Ashenvale":1440,"Stonetalon Mountains":1442,"Desolace":1443,"Feralas":1444,"Dustwallow Marsh":1445,"Tanaris":1446,
 "Azshara":1447,"Felwood":1448,"Un'Goro Crater":1449,"Silithus":1451,"Winterspring":1452}

objects = collections.defaultdict(list)
for oid, name in re.findall(r'\[(\d+)\]=\{kind="herb",name="([^"]+)"', (root/'Data/Nodes.lua').read_text()):
    objects[name].append(int(oid))
spawns = {}
for m in re.finditer(r'\n    \[(\d+)\] = \{(.*?)\n    \},', (root/'Data/Spawns.lua').read_text(), re.S):
    spawns[int(m.group(1))] = {int(k): [float(x) for x in re.findall(r'[\d.]+', v)]
                               for k, v in re.findall(r'\[(\d+)\] = \{([^}]*)\}', m.group(2))}

stops, herb = collections.defaultdict(list), None
for line in (root/'tools/data/warcraftmaps_herb_stops.txt').read_text().splitlines():
    line = line.strip()
    if not line or line.startswith('#'): continue
    if line.startswith('H '): herb = line[2:]; continue
    zone, x, y, n = line.split('|')
    stops[herb].append((ZONES[zone], round(float(x)/100, 3), round(float(y)/100, 3), int(n)))

out, total = [], 0
for herb in sorted(stops):
    ids = objects[herb]; assert ids, herb
    main = max(ids, key=lambda o: sum(len(v) for v in spawns.get(o, {}).values()))
    known = collections.defaultdict(list)
    for o in ids:
        for z, v in spawns.get(o, {}).items(): known[z] += list(zip(v[::2], v[1::2]))
    add = collections.defaultdict(list)
    for z, x, y, n in stops[herb]:
        if n <= 0: continue
        pool = known[z] + add[z]
        if all(math.hypot(px-x, py-y) >= MATCH for px, py in pool):
            add[z].append((x, y))
    add = {z: p for z, p in add.items() if p}
    if not add: continue
    count = sum(len(v) for v in add.values()); total += count
    zones = ',\n  '.join(f"[{z}]={{{', '.join(f'{x:g},{y:g}' for x, y in pts)}}}" for z, pts in sorted(add.items()))
    out.append(f' -- {herb}: {count} stops\n [{main}]={{\n  {zones}}},')

lua = f'''-- Herb stops Nexus's spawn list was missing (generated by tools/bake_warcraftmaps.py; do not edit).
-- Stop positions: warcraftmaps.com herb pages (Classic spawn data on Forever terrain), fetched Nov 2026.
-- Credit: WarcraftMaps, https://warcraftmaps.com/gold/herb-spots, client build 1.60.1.70938.
-- Each is a stop centre (one point); a spot is skipped at load if Nexus already has a spawn within 2% of it.
local _, N = ...
local extra = {{
{chr(10).join(out)}
}}
N.spawns = N.spawns or {{}}
local added = 0
for object, zones in pairs(extra) do
 N.spawns[object] = N.spawns[object] or {{}}
 for map, pts in pairs(zones) do
  local list = N.spawns[object][map] or {{}}
  N.spawns[object][map] = list
  for i = 1, #pts, 2 do
   local x, y, near = pts[i], pts[i+1], false
   for j = 1, #list - 1, 2 do
    local dx, dy = list[j] - x, list[j+1] - y
    if dx*dx + dy*dy < {MATCH*MATCH:g} then near = true break end
   end
   if not near then list[#list+1] = x; list[#list+1] = y; added = added + 1 end
  end
 end
end
N.extraHerbStops = added
N.extraLotusSpots = added -- kept for older callers
'''
(root/'Data/SpawnsExtra.lua').write_text(lua, newline='\n')
print('stops added:', total)
