"""Build Data/SpawnsOre.lua from tools/data/wowhead_forever_ore.txt.

The input holds mining spots from Wowhead's WoW Forever object pages (map data) that Nexus's
spawn list did not have: a spot was kept only when no spawn of the same ore was within 1% of
the map. Points are packed as base-36 pairs (x*1000, y*1000). Re-run after updating the input.
"""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
lines = [l.strip() for l in (root/'tools/data/wowhead_forever_ore.txt').read_text().splitlines()]
raw = ''.join(l for l in lines if l and not l.startswith('#'))
data, total = {}, 0
for part in raw.split(';'):
    oid, map_id, pts = part.split('.')
    assert len(pts) % 4 == 0, part[:30]
    xy = []
    for i in range(0, len(pts), 4):
        x, y = int(pts[i:i+2], 36) / 1000, int(pts[i+2:i+4], 36) / 1000
        assert 0 <= x <= 1 and 0 <= y <= 1, part[:30]
        xy += [x, y]
    data.setdefault(int(oid), {})[int(map_id)] = xy
    total += len(xy) // 2
out = ['-- Mining spots Nexus\'s spawn list was missing (generated by tools/bake_wowhead_ore.py; do not edit).',
       '-- Source: Wowhead WoW Forever object map data (wowhead.com/forever/objects/mineral-veins), fetched 2026-11-25.',
       f'-- {total} spots, each kept only when no spawn of the same ore was within 1% of the map.',
       'local _, N = ...', 'local extra = {']
for oid in sorted(data):
    out.append(f' [{oid}]={{')
    for m in sorted(data[oid]):
        out.append(f'  [{m}]={{' + ','.join(f'{v:g}' for v in data[oid][m]) + '},')
    out.append(' },')
out += ['}', 'N.spawns = N.spawns or {}', 'local added = 0',
 'for object, zones in pairs(extra) do',
 ' N.spawns[object] = N.spawns[object] or {}',
 ' for map, pts in pairs(zones) do',
 '  local list = N.spawns[object][map] or {}',
 '  N.spawns[object][map] = list',
 '  for i = 1, #pts, 2 do',
 '   local x, y, near = pts[i], pts[i+1], false',
 '   for j = 1, #list - 1, 2 do',
 '    local dx, dy = list[j] - x, list[j+1] - y',
 '    if dx*dx + dy*dy < 0.000025 then near = true break end',
 '   end',
 '   if not near then list[#list+1] = x; list[#list+1] = y; added = added + 1 end',
 '  end',
 ' end',
 'end',
 'N.extraOreSpots = added', '']
(root/'Data/SpawnsOre.lua').write_text('\n'.join(out))
print(f'Wrote {total} spots across {len(data)} ore objects')
