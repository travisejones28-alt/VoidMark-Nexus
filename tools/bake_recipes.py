"""Bake Data/RecipeSources.lua from the MIT-licensed wow-classic-items dataset.

Usage: python3 tools/bake_recipes.py PATH/TO/wow-classic-items/data/json

Keeps Classic recipe items only (skill 300 or less, item ID below 23500, no
Jewelcrafting or class books). Each profession becomes one long string, one
line per recipe item, so the data costs little memory until the Missing view
parses the profession you open:

  itemID|recipe name|skill|kind|npc|faction|cost|zone|quest|drop chance

kind: V vendor, B boss drop, Z zone drop, R world drop, Q quest reward, blank unknown.
faction: A Alliance, H Horde, blank both/unknown.
"""
from pathlib import Path
import json
import re
import sys

PREFIXES = ("Recipe: ", "Plans: ", "Pattern: ", "Schematic: ", "Formula: ", "Manual: ")
KIND = {"Vendor": "V", "Boss Drop": "B", "Zone Drop": "Z", "Rare Drop": "R", "Quest": "Q"}
FACTION = {"Alliance": "A", "Horde": "H"}

src = Path(sys.argv[1] if len(sys.argv) > 1 else ".")
items = json.loads((src / "data.json").read_text(encoding="utf-8"))
zones = {z["id"]: z["name"] for z in json.loads((src / "zones.json").read_text(encoding="utf-8"))}


def clean(text):
    return re.sub(r"[|\r\n\]\[]", " ", str(text or "")).replace(" ", " ").strip()


def skill_of(item):
    for t in item["tooltip"]:
        m = re.match(r"Requires (.+?) \((\d+)\)", t["label"])
        if m:
            return m.group(1), int(m.group(2))
    return None, None


def recipe_name(item):
    name = item["name"]
    for p in PREFIXES:
        if name.startswith(p):
            return name[len(p):]
    return name


by_prof = {}
for item in items:
    if item.get("class") != "Recipe" or item.get("subclass") in ("Jewelcrafting", "Book"):
        continue
    prof, skill = skill_of(item)
    if skill is None or skill > 300 or item["itemId"] >= 23500:
        continue
    prof = item["subclass"]
    if recipe_name(item) == item["name"]:
        continue  # rank books such as "Expert Cookbook" teach a rank, not a recipe
    s = item.get("source") or {}
    kind = KIND.get(s.get("category"), "")
    npc, faction, cost, zone, quest, chance = "", "", "", "", "", ""
    if kind == "V":
        npc, faction, cost = clean(s.get("name")), FACTION.get(s.get("faction"), ""), str(s.get("cost") or "")
    elif kind in ("B", "Z", "R"):
        npc = clean(s.get("name"))
        zone = clean(zones.get(s.get("zone"), "")) if s.get("zone") else ""
        if s.get("dropChance"):
            chance = "%g" % round(s["dropChance"] * 100, 2)
    elif kind == "Q":
        qs = s.get("quests") or []
        if qs:
            quest = clean(qs[0].get("name"))
            faction = FACTION.get(qs[0].get("faction"), "")
    line = "|".join([str(item["itemId"]), clean(recipe_name(item)), str(skill), kind, npc, faction, cost, zone, quest, chance])
    by_prof.setdefault(prof, []).append((skill, item["itemId"], line))

out = ["local _, N = ...",
       "-- Generated by tools/bake_recipes.py from wow-classic-items (MIT, see Licenses/wow-classic-items.txt).",
       "-- Classic recipe items and where they come from. Forever can differ: sources you",
       "-- see in game (Trainers.lua / RecipeFinder.lua) are shown first and marked as seen.",
       "-- itemID|recipe|skill|kind|npc|faction|cost|zone|quest|drop%",
       "N.RecipeSourceData = {"]
total = 0
for prof in sorted(by_prof):
    rows = sorted(by_prof[prof])
    total += len(rows)
    out.append(" [%s] = [[" % json.dumps(prof))
    out.extend(r[2] for r in rows)
    out.append("]],")
out.append("}")
dest = Path(__file__).resolve().parents[1] / "Data" / "RecipeSources.lua"
dest.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(f"Wrote {total} recipe items for {len(by_prof)} professions to {dest}")
